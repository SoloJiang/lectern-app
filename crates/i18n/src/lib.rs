//! Fluent resources and language switching (en, zh-CN).
//!
//! The resources in `locales/` are parsed, checked and compiled into static
//! tables by `build.rs`; nothing is parsed at run time and the binary contains
//! no Fluent parser. Keys are generated constants, so a mistyped key, or a key
//! passed to the wrong method, does not compile. See docs/design/i18n.md.
//!
//! ```
//! use lectern_i18n::{Args, Locale, Strings, keys};
//!
//! let strings = Strings::of(Locale::negotiate(["zh-Hans-CN", "en-US"]));
//! assert_eq!(strings.get(keys::review::LOOKS_GOOD), "看起来没问题");
//! let changed = strings.format(keys::review::FILES_CHANGED, &Args::new().num("count", 3));
//! assert_eq!(changed, "3 个文件有改动");
//!
//! let en = Strings::of(Locale::En);
//! assert_eq!(en.format(keys::review::FILES_CHANGED, &Args::new().num("count", 1)), "1 file changed");
//! // String arguments are wrapped in directional isolates.
//! let reviewing = en.format(keys::review::REVIEWING, &Args::new().str("path", "src/lib.rs"));
//! assert_eq!(reviewing, "Reviewing \u{2068}src/lib.rs\u{2069}");
//! ```

