/// Generated by build.rs from `locales/en/*.ftl`: one module per file, one
/// constant per message value or attribute.
///
/// `review-looks-good` → `keys::review::LOOKS_GOOD: Key`; its attribute
/// `.tooltip` → `keys::review::LOOKS_GOOD_TOOLTIP: Key`;
/// `review-files-changed`, which uses `$count` → `keys::review::FILES_CHANGED: FmtKey`.
/// Each `FmtKey` constant's documentation lists its variables and their types.
pub mod keys {
    include!(concat!(env!("OUT_DIR"), "/keys.rs"));
}

/// A message or attribute without variables: an index into the compiled
/// tables. Only the generated [`keys`] module constructs one.
///
/// Passing a `Key` to [`Strings::format`] does not compile:
///
/// ```compile_fail
/// use lectern_i18n::{Args, Locale, Strings, keys};
/// Strings::of(Locale::En).format(keys::review::LOOKS_GOOD, &Args::new());
/// ```
#[derive(Clone, Copy, Debug)]
pub struct Key {
    index: u16,
}

impl Key {
    pub(crate) const fn new(index: u16) -> Key {
        Key { index }
    }

    /// The Fluent message ID: `review-looks-good`, or `review-looks-good.tooltip`
    /// for an attribute. `ui::Text` carries it so that the UI probe can name
    /// the message a label came from (docs/design/ui.md「文本」).
    pub fn name(&self) -> &'static str {
        table::NAMES[usize::from(self.index)]
    }
}

/// A message or attribute with variables. A different type from [`Key`]:
/// passing it to [`Strings::get`] does not compile.
///
/// ```compile_fail
/// use lectern_i18n::{Locale, Strings, keys};
/// Strings::of(Locale::En).get(keys::review::FILES_CHANGED);
/// ```
#[derive(Clone, Copy, Debug)]
pub struct FmtKey {
    index: u16,
}

impl FmtKey {
    pub(crate) const fn new(index: u16) -> FmtKey {
        FmtKey { index }
    }

    /// The Fluent message ID, as [`Key::name`].
    pub fn name(&self) -> &'static str {
        table::NAMES[usize::from(self.index)]
    }
}
