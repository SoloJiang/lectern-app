//! Turns a [`Compiled`] set of resources into Rust source: the static tables
//! (`table.rs`, included by src/table.rs) and the `keys` module (`keys.rs`,
//! included by src/lib.rs).

use std::fmt::Write as _;

use crate::compile::{Compiled, LOCALES, Node, VarType, VariantKey};

pub fn table_rs(compiled: &Compiled) -> String {
    let mut out = String::new();
    out.push_str("// @generated by build.rs from locales/. Do not edit.\n\n");
    let len = compiled.entries.len();
    assert!(
        len <= usize::from(u16::MAX),
        "too many strings for a u16 index"
    );
    writeln!(out, "pub(crate) const LEN: usize = {len};\n").unwrap();

    out.push_str("/// Message ID and attribute of every slot, for diagnostics.\n");
    out.push_str("pub(crate) static NAMES: [&str; LEN] = [\n");
    for entry in &compiled.entries {
        writeln!(out, "    {:?},", entry.name()).unwrap();
    }
    out.push_str("];\n\n");

    out.push_str("/// Variables of every slot; `Part::Var` and `Part::Select` index into these.\n");
    out.push_str("pub(crate) static VARS: [&[(&str, VarType)]; LEN] = [\n");
    for entry in &compiled.entries {
        out.push_str("    &[");
        for (i, (name, ty)) in entry.vars.iter().enumerate() {
            if i > 0 {
                out.push_str(", ");
            }
            write!(out, "({name:?}, {})", var_type(*ty)).unwrap();
        }
        out.push_str("],\n");
    }
    out.push_str("];\n");

    for (locale, table) in LOCALES.iter().zip(&compiled.tables) {
        writeln!(
            out,
            "\npub(crate) static {}: [&[Part]; LEN] = [",
            locale.table
        )
        .unwrap();
        for nodes in table {
            out.push_str("    ");
            parts(&mut out, nodes);
            out.push_str(",\n");
        }
        out.push_str("];\n");
    }
    out
}

pub fn keys_rs(compiled: &Compiled) -> String {
    let mut out = String::new();
    out.push_str("// @generated by build.rs from locales/en/*.ftl. Do not edit.\n");
    let en = &compiled.tables[0];
    for module in &compiled.modules {
        writeln!(
            out,
            "\n#[doc = {:?}]",
            format!("Strings in `{}.ftl`.", module.file)
        )
        .unwrap();
        writeln!(out, "pub mod {} {{", module.ident).unwrap();
        for index in module.entries.clone() {
            let entry = &compiled.entries[index];
            let preview = preview(&en[index], &entry.vars);
            writeln!(
                out,
                "    #[doc = {:?}]",
                format!("`{}`: {preview}", entry.name())
            )
            .unwrap();
            if entry.vars.is_empty() {
                writeln!(
                    out,
                    "    pub const {}: crate::Key = crate::Key::new({index});",
                    entry.const_name
                )
                .unwrap();
            } else {
                let vars: Vec<String> = entry
                    .vars
                    .iter()
                    .map(|(name, ty)| format!("`${name}` ({})", ty.describe()))
                    .collect();
                writeln!(out, "    #[doc = \"\"]").unwrap();
                writeln!(
                    out,
                    "    #[doc = {:?}]",
                    format!("Variables: {}.", vars.join(", "))
                )
                .unwrap();
                writeln!(
                    out,
                    "    pub const {}: crate::FmtKey = crate::FmtKey::new({index});",
                    entry.const_name
                )
                .unwrap();
            }
        }
        out.push_str("}\n");
    }
    out
}

fn var_type(ty: VarType) -> &'static str {
    match ty {
        VarType::Num => "VarType::Num",
        VarType::Str => "VarType::Str",
        VarType::Any => "VarType::Any",
    }
}

fn parts(out: &mut String, nodes: &[Node]) {
    out.push_str("&[");
    for (i, node) in nodes.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        match node {
            Node::Text(text) => write!(out, "Part::Text({text:?})").unwrap(),
            Node::Var(var) => write!(out, "Part::Var({var})").unwrap(),
            Node::Select { var, arms, default } => {
                write!(
                    out,
                    "Part::Select {{ var: {var}, default: {default}, arms: &["
                )
                .unwrap();
                for (j, (key, arm)) in arms.iter().enumerate() {
                    if j > 0 {
                        out.push_str(", ");
                    }
                    out.push('(');
                    match key {
                        VariantKey::Plural("one") => {
                            out.push_str("Selector::Plural(PluralCategory::One)")
                        }
                        VariantKey::Plural("other") => {
                            out.push_str("Selector::Plural(PluralCategory::Other)")
                        }
                        // Validation only lets through the categories of en and zh-CN.
                        VariantKey::Plural(other) => {
                            panic!("plural category {other} has no runtime variant")
                        }
                        VariantKey::Exact(value) => {
                            write!(out, "Selector::Exact({value:?})").unwrap()
                        }
                        VariantKey::Str(value) => write!(out, "Selector::Str({value:?})").unwrap(),
                    }
                    out.push_str(", ");
                    parts(out, arm);
                    out.push(')');
                }
                out.push_str("] }");
            }
        }
    }
    out.push(']');
}

/// The en text for the key's doc comment: variables as `{ $name }`, selects
/// by their default variant.
fn preview(nodes: &[Node], vars: &[(String, VarType)]) -> String {
    let mut out = String::new();
    for node in nodes {
        match node {
            Node::Text(text) => out.push_str(text),
            Node::Var(var) => write!(out, "{{ ${} }}", vars[*var].0).unwrap(),
            Node::Select { arms, default, .. } => out.push_str(&preview(&arms[*default].1, vars)),
        }
    }
    out
}
