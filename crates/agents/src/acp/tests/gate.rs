//! `can_prompt` 的检查（`prompt_gate_*`）。

use lectern_services::conversation::{AcpProgram, Conversations, Unavailable};
use lectern_services::session::{Agent, Place, ResumeCommand, SessionSource};

use super::support::*;

fn rig_with_programs() -> (Rig, tempfile::TempDir) {
    let dir = tempfile::tempdir().unwrap();
    install(dir.path(), "claude-agent-acp");
    install(dir.path(), "codex-acp");
    (Rig::new(dir.path()), dir)
}

fn can_prompt(
    rig: &Rig,
    session: &lectern_services::session::SessionKey,
) -> Result<(), Unavailable> {
    let _interest = rig.engine.watch(session);
    rig.engine.snapshot(session).unwrap().can_prompt.clone()
}

#[test]
fn prompt_gate_passes_the_checks_then_stops_at_unsupported() {
    let (rig, _dir) = rig_with_programs();
    let session = rig.claude_session();
    // Everything holds; the process half is not implemented yet.
    assert_eq!(can_prompt(&rig, &session), Err(Unavailable::Unsupported));
    let codex = key(&codex_source(), CODEX_SESSION);
    rig.codex.add(
        &codex,
        Spec::located(&codex, folder("/work/project"), &Agent::Codex),
    );
    assert_eq!(can_prompt(&rig, &codex), Err(Unavailable::Unsupported));
}

#[test]
fn prompt_gate_refuses_what_cannot_be_resumed() {
    let (rig, _dir) = rig_with_programs();
    let session = rig.claude_session();

    // A session the source does not list.
    let unknown = key(&claude_source(), "c1a0de00-9999-4999-8999-000000000009");
    assert_eq!(can_prompt(&rig, &unknown), Err(Unavailable::NotResumable));

    // A sub-agent session.
    rig.claude.set_spec(&session, |spec| spec.parent = true);
    assert_eq!(can_prompt(&rig, &session), Err(Unavailable::NotResumable));
    rig.claude.set_spec(&session, |spec| spec.parent = false);

    // The source gives no resume command.
    rig.claude.set_spec(&session, |spec| spec.resume = None);
    assert_eq!(can_prompt(&rig, &session), Err(Unavailable::NotResumable));

    // The command is the other agent's.
    rig.claude.set_spec(&session, |spec| {
        spec.resume = Some(ResumeCommand::Codex {
            session_id: CLAUDE_SESSION.into(),
        });
    });
    assert_eq!(can_prompt(&rig, &session), Err(Unavailable::NotResumable));

    // The command names another session.
    rig.claude.set_spec(&session, |spec| {
        spec.resume = Some(ResumeCommand::ClaudeCode {
            session_id: CODEX_SESSION.into(),
        });
    });
    assert_eq!(can_prompt(&rig, &session), Err(Unavailable::NotResumable));
}

#[test]
fn prompt_gate_refuses_a_session_id_that_is_not_a_canonical_uuid() {
    let (rig, _dir) = rig_with_programs();
    for id in [
        "--help",
        "C1A0DE00-1111-4111-8111-0000000000A1",
        "not-a-uuid",
    ] {
        let session = key(&claude_source(), id);
        let project = folder("/work/project");
        rig.projects.set_open(vec![project.clone()]);
        rig.claude.add(
            &session,
            Spec::located(&session, project, &Agent::ClaudeCode),
        );
        assert_eq!(
            can_prompt(&rig, &session),
            Err(Unavailable::NotResumable),
            "{id}"
        );
    }
}

#[test]
fn prompt_gate_refuses_a_source_that_is_not_built_in() {
    let (rig, _dir) = rig_with_programs();
    // An extension's source: its ID is generated by the host and has no program.
    let other = FakeSource::new(
        lectern_services::session::SourceId("ext.somebody.sessions".into()),
        Agent::Other("somebody".into()),
    );
    let session = key(&other.id(), CLAUDE_SESSION);
    other.add(
        &session,
        Spec::located(&session, folder("/work/project"), &Agent::ClaudeCode),
    );
    let engine = engine_with(vec![other], rig.projects.clone(), _dir.path());
    let _interest = engine.watch(&session);
    assert_eq!(
        engine.snapshot(&session).unwrap().can_prompt,
        Err(Unavailable::NotResumable)
    );
}

#[test]
fn prompt_gate_refuses_a_session_outside_the_open_projects() {
    let (rig, _dir) = rig_with_programs();
    let session = rig.claude_session();
    // Keep the session watched: the snapshot goes away with the last interest.
    let _interest = rig.engine.watch(&session);
    rig.projects.set_open(vec![]);
    rig.engine.on_projects_changed();
    assert_eq!(can_prompt(&rig, &session), Err(Unavailable::OutsideProject));
    rig.projects.set_open(vec![folder("/work/project")]);
    rig.engine.on_projects_changed();
    assert_eq!(
        rig.engine.snapshot(&session).unwrap().can_prompt,
        Err(Unavailable::Unsupported)
    );
    // The project closes while the session is watched.
    rig.projects.set_open(vec![]);
    rig.engine.on_projects_changed();
    assert_eq!(
        rig.engine.snapshot(&session).unwrap().can_prompt,
        Err(Unavailable::OutsideProject)
    );
    // A session that is not placed in a project.
    rig.claude
        .set_spec(&session, |spec| spec.place = Place::Pending);
    rig.engine
        .on_sessions_changed(&changed(&claude_source(), &session));
    assert_eq!(
        rig.engine.snapshot(&session).unwrap().can_prompt,
        Err(Unavailable::OutsideProject)
    );
}

#[test]
fn prompt_gate_reports_a_missing_program_after_the_other_checks() {
    // No adapter on the PATH.
    let dir = tempfile::tempdir().unwrap();
    let rig = Rig::new(dir.path());
    let session = rig.claude_session();
    let _interest = rig.engine.watch(&session);
    assert_eq!(
        can_prompt(&rig, &session),
        Err(Unavailable::NotInstalled(AcpProgram::ClaudeCode))
    );
    // The earlier checks win: a session outside the projects is not "not installed".
    rig.projects.set_open(vec![]);
    rig.engine.on_projects_changed();
    assert_eq!(
        rig.engine.snapshot(&session).unwrap().can_prompt,
        Err(Unavailable::OutsideProject)
    );
}
